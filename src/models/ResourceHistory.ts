/**
 * История изменений ресурсов (кровь, здоровье и пр.)
 */
export type ResourceHistory<T> = {
  /**
   * Дата события в миллисекундах (Unix timestamp).
   * Пример: 1732598400000.
   */
  date: number;

  /**
   * Эффект изменения ресурса.
   * Может быть числом (например, -2 пункта крови) или объектом
   * (например, { healthLevel: 'critical', reason: 'bleeding' }).
   */
  effect: T;

  /**
   * Описание причины изменения, уже подготовленное для отображения.
   */
  description: string;
};
